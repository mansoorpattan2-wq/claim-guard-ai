import {
  Activity,
  CheckCircle2,
  AlertTriangle,
  Clock,
  ChevronRight,
} from "lucide-react";
import { ExecutionStep } from "@/lib/api";
import { Badge } from "./ui";
export default function AgentTrace({ steps }: { steps: ExecutionStep[] }) {
  return (
    <div className="structured-trace">
      {!steps.length && (
        <p className="empty">
          Named checks will appear here as execution completes.
        </p>
      )}
      {steps.map((s, i) => (
        <details
          className="trace-step"
          key={s.job_id + "-" + s.agent + "-" + i}
        >
          <summary>
            <span className={"trace-icon " + s.status.toLowerCase()}>
              {s.status === "FAILED" ? (
                <AlertTriangle size={18} />
              ) : s.status === "RUNNING" ? (
                <Activity size={18} />
              ) : (
                <CheckCircle2 size={18} />
              )}
            </span>
            <div>
              <strong>{s.agent}</strong>
              <small>
                {s.inputs_summary || "Persisted claim and source documents"}
              </small>
            </div>
            <span className="trace-duration">
              <Clock size={12} />
              {s.duration_ms === undefined
                ? "Legacy run"
                : s.duration_ms === 0
                  ? "Recorded summary"
                  : s.duration_ms + " ms"}
            </span>
            <Badge status={s.status} />
          </summary>
          <div className="trace-body">
            <div className="trace-metadata">
              <div>
                Started
                <strong>{s.started_at || "Not recorded in legacy run"}</strong>
              </div>
              <div>
                Ended<strong>{s.ended_at || "Pending / legacy run"}</strong>
              </div>
              <div>
                Tools
                <strong>
                  {s.tools?.join(" · ") ||
                    "Deterministic rules (legacy summary)"}
                </strong>
              </div>
              <div>
                Next transition
                <strong>{s.next_transition || "See claim state"}</strong>
              </div>
            </div>
            <div className="trace-evidence">
              <p>
                Evidence references:{" "}
                <b>
                  {s.evidence_refs?.join(", ") ||
                    "No source generated by this check"}
                </b>
              </p>
              <p>
                Findings generated:{" "}
                <b>{s.finding_refs?.join(", ") || "None recorded"}</b>
              </p>
            </div>
            {s.error && (
              <div className="error-banner">
                {s.error} · Retry via intake job controls.
              </div>
            )}
            <details>
              <summary>
                Structured output <ChevronRight size={13} />
              </summary>
              <pre className="document-text">
                {JSON.stringify(s.output || {}, null, 2)}
              </pre>
            </details>
          </div>
        </details>
      ))}
    </div>
  );
}
